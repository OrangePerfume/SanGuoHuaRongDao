PIECE_IDS = (
    'caocao', 'guanyu', 'zhangfei', 'zhaoyun', 'machao', 'huangzhong',
    'soldier', 'soldier', 'soldier', 'soldier',
)


def normalize_language(language: object) -> str:
    return language if isinstance(language, str) and language in STRINGS else DEFAULT_LANGUAGE


def tr(language: str, key: str, /, **kwargs: object) -> str:
    value = STRINGS[normalize_language(language)][key]
    return value.format(**kwargs) if kwargs else value


def piece_name(language: str, index: int, /, tile: bool = False) -> str:
    if not 0 <= index < len(PIECE_IDS):
        raise IndexError(index)
    name = PIECE_IDS[index]
    return tr(language, 'piece_soldier_tile' if tile and name == 'soldier' else 'piece_' + name)


def selected_names(language: str, indices: tuple[int, ...]) -> str:
    if not indices:
        return tr(language, 'selection_none')
    names = tr(language, 'selection_sep').join(piece_name(language, i) for i in indices)
    return tr(language, 'selection_many', count=len(indices), names=names) if len(indices) > 1 else names
